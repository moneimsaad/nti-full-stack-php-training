<?php


function calculator ($Num1,$Num2){

    echo "Multiplication = $Num1 * $Num2 = " . ($Num1 * $Num2) . "\n" ;       // Multiplication = 5 * 5 = 25
    echo "Difference     = $Num1 - $Num2 = " . ($Num1 - $Num2) . "\n" ;       // Difference     = 5 - 5 = 0
    echo "Division       = $Num1 / $Num2 = " . ($Num1 / $Num2) . "\n" ;       // Division       = 5 / 5 = 1

} 

calculator(5,5);


?>